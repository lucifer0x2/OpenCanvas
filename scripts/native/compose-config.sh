#!/bin/bash
# Generates <root>/process-compose.yaml for PostgreSQL and the server. Regenerate, never edit.
set -euo pipefail
umask 077
HERE=$(cd "$(dirname "$0")" && pwd -P)
# shellcheck source=scripts/native/deploy-common.sh
source "$HERE/deploy-common.sh"

if [[ "${1:-}" == --help || "${1:-}" == -h ]]; then
  cat <<'EOF'
Usage: compose-config.sh [--yes]
Writes process-compose.yaml into the runtime root (OPENCANVAS_ROOT, default
~/Library/Application Support/OpenCanvas) from config/native.conf and the local port in
config/server.env, then validates it with process-compose --dry-run when available.
Called by migrate-to-process-compose.sh; process-compose reads it at its next start.
--yes skips the confirmation on the live root.
EOF
  exit 0
fi
ASSUME_YES=false
[[ "${1:-}" != --yes ]] || { ASSUME_YES=true; shift; }
[[ $# == 0 ]] || die "Usage: compose-config.sh [--yes] (see --help)"
root_init
confirm_live "Regenerate process-compose.yaml in the live root $ROOT?"
load_native_conf
local_port=$(port_value OPENCANVAS_PORT "$SERVER_ENV")

# YAML single-quoted scalar; the inner text is a bash command line built with printf %q.
yq() { local value=${1//\'/\'\'}; printf "'%s'" "$value"; }
cmd() { local line; line=$(printf '%q ' "$@"); yq "${line% }"; }

logs() {
  cat <<EOF
    log_location: $(yq "$ROOT/logs/$1.log")
    log_configuration:
      disable_json: true
      no_color: true
      no_metadata: true
      add_timestamp: true
      flush_each_line: true
      rotation:
        max_size_mb: 20
        max_backups: 5
EOF
}

temporary=$(mktemp "$ROOT/.process-compose.yaml.XXXXXX")
trap 'rm -f "$temporary"' EXIT
cat > "$temporary" <<EOF
# Generated by scripts/native/compose-config.sh. Regenerate instead of editing.
version: "0.5"
is_strict: true
disable_env_expansion: true
ordered_shutdown: true
log_level: info
shell:
  shell_command: /bin/bash
  shell_argument: -c
processes:
  postgres:
    description: PostgreSQL 16 cluster; SIGINT requests a fast clean shutdown
    command: $(cmd "$RUNTIME/scripts/run-postgres.sh" "$NATIVE_CONF")
    is_template_disabled: true
    working_dir: $(yq "$ROOT")
$(logs postgres)
    readiness_probe:
      exec:
        command: $(cmd "$PG_BIN/pg_isready" -q -h "$PGADMIN_HOST" -p "$PGPORT")
      initial_delay_seconds: 1
      period_seconds: 5
      timeout_seconds: 5
      failure_threshold: 60
    availability:
      restart: on_failure
      backoff_seconds: 5
    shutdown:
      signal: 2
      parent_only: true
      timeout_seconds: 60
  server:
    description: OpenCanvas server from runtime/current; SIGINT starts its graceful shutdown
    command: $(cmd "$RUNTIME/scripts/run-server.sh" "$SERVER_ENV")
    is_template_disabled: true
    working_dir: $(yq "$ROOT")
$(logs server)
    depends_on:
      postgres:
        condition: process_healthy
    readiness_probe:
      http_get:
        host: 127.0.0.1
        scheme: http
        port: $local_port
        path: /api/v1/viewer
      initial_delay_seconds: 1
      period_seconds: 2
      timeout_seconds: 5
      failure_threshold: 30
    availability:
      restart: on_failure
      backoff_seconds: 5
    shutdown:
      signal: 2
      parent_only: true
      timeout_seconds: 30
EOF
chmod 600 "$temporary"
if [[ -x "$PC_BIN" ]]; then
  (cd "$ROOT" && "$PC_BIN" up --dry-run --no-server --disable-dotenv --tui=false --config "$temporary" \
    --log-file "$ROOT/logs/process-compose-dry-run.log" >/dev/null) ||
    die "process-compose rejected the generated configuration"
fi
mv "$temporary" "$ROOT/process-compose.yaml"
trap - EXIT
say "Wrote $ROOT/process-compose.yaml"
