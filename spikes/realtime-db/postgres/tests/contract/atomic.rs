use crate::{batch, db};
use serde_json::json;
use std::time::Duration;

#[tokio::test]
async fn same_project_race_and_stale_replay_are_atomic() {
    let (url, id) = project("race").await;
    seed(&url, &id).await;
    let a = request(&id, "a", 1, vec![update("root", 2)]);
    let b = request(&id, "b", 1, vec![update("root", 3)]);
    let (left, right) = tokio::join!(batch::execute(&url, &a), batch::execute(&url, &b));
    assert_eq!(usize::from(left.is_ok()) + usize::from(right.is_ok()), 1);
    let conflict = left.as_ref().err().or(right.as_ref().err()).unwrap();
    assert_eq!(conflict.code, "REVISION_CONFLICT");
    assert_eq!(conflict.current_revision, Some(2));
    let winner = if left.is_ok() { a } else { b };
    let original = left.ok().or_else(|| right.ok()).unwrap();
    batch::execute(&url, &request(&id, "later", 2, vec![update("paired", 4)]))
        .await
        .unwrap();
    let mut replay = batch::execute(&url, &winner).await.unwrap();
    assert_eq!(replay["committedRevision"], 2);
    assert_eq!(replay["replayed"], true);
    replay["replayed"] = json!(false);
    assert_eq!(
        replay, original,
        "replay preserves the complete stored result"
    );
    let mut collision = winner;
    collision.operations = vec![update("root", 9)];
    assert_eq!(
        batch::execute(&url, &collision).await.unwrap_err().code,
        "IDEMPOTENCY_KEY_REUSED"
    );
    assert_eq!(counts(&url, &id).await, [3, 2, 3, 3]);
    clean(&url, &id).await;
}

#[tokio::test]
async fn held_project_lock_does_not_block_another_project() {
    let (url, a) = project("locked").await;
    let (_, b) = project("independent").await;
    let mut locker = db::connect(&url).await.unwrap();
    let pid: i32 = locker
        .query_one("SELECT pg_backend_pid()", &[])
        .await
        .unwrap()
        .get(0);
    let tx = locker.transaction().await.unwrap();
    tx.query_one(
        "SELECT revision FROM projects WHERE project_id=$1 FOR UPDATE",
        &[&a],
    )
    .await
    .unwrap();
    let blocked_url = url.clone();
    let req = request(&a, "shared_key", 0, vec![page("same_id")]);
    let blocked = tokio::spawn(async move { batch::execute(&blocked_url, &req).await });
    let observer = db::connect(&url).await.unwrap();
    tokio::time::timeout(Duration::from_secs(3), async {
        loop {
            let waiting: i64 = observer
                .query_one(
                    "SELECT count(*) FROM pg_stat_activity WHERE $1=ANY(pg_blocking_pids(pid))",
                    &[&pid],
                )
                .await
                .unwrap()
                .get(0);
            if waiting > 0 {
                break;
            }
            tokio::time::sleep(Duration::from_millis(10)).await;
        }
    })
    .await
    .expect("same-project write must actually wait on held DB lock");
    assert!(!blocked.is_finished());
    let independent = tokio::time::timeout(
        Duration::from_secs(1),
        batch::execute(&url, &request(&b, "shared_key", 0, vec![page("same_id")])),
    )
    .await
    .expect("another project must commit before lock release")
    .unwrap();
    assert_eq!(independent["committedRevision"], 1);
    assert!(!blocked.is_finished());
    tx.commit().await.unwrap();
    assert_eq!(blocked.await.unwrap().unwrap()["committedRevision"], 1);
    clean(&url, &a).await;
    clean(&url, &b).await;
}

#[tokio::test]
async fn late_validation_and_late_sql_failure_leave_no_partial_records() {
    let (url, id) = project("rollback").await;
    seed(&url, &id).await;
    let before = db::snapshot(&url, &id).await.unwrap();
    let invalid = request(
        &id,
        "retryable",
        1,
        vec![
            update("root", 20),
            json!({"op":"create_node","id":"orphan","parentId":"missing","kind":"group","props":{}}),
        ],
    );
    assert_eq!(
        batch::execute(&url, &invalid).await.unwrap_err().code,
        "VALIDATION_FAILED"
    );
    assert_eq!(db::snapshot(&url, &id).await.unwrap(), before);
    let client = db::connect(&url).await.unwrap();
    // Fail the final insert after entities, project revision and commit were written.
    // IDs are generated by this suite, never supplied by an external caller.
    let trigger = format!("fail_{}", id);
    client.batch_execute(&format!("CREATE FUNCTION pg_temp.{trigger}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'spike rollback probe'; END $$; CREATE TRIGGER {trigger} BEFORE INSERT ON idempotency FOR EACH ROW WHEN (NEW.project_id='{id}') EXECUTE FUNCTION pg_temp.{trigger}();")).await.unwrap();
    let corrected = request(&id, "retryable", 1, vec![update("root", 20)]);
    assert_eq!(
        batch::execute(&url, &corrected).await.unwrap_err().code,
        "INTERNAL_ERROR"
    );
    client
        .batch_execute(&format!(
            "DROP TRIGGER {trigger} ON idempotency; DROP FUNCTION pg_temp.{trigger}();"
        ))
        .await
        .unwrap();
    assert_eq!(counts(&url, &id).await, [1, 2, 1, 1]);
    assert_eq!(db::snapshot(&url, &id).await.unwrap(), before);
    assert_eq!(
        batch::execute(&url, &corrected).await.unwrap()["committedRevision"],
        2
    );
    clean(&url, &id).await;
}
